/**
 * Get Ramayana exercises by type
 */
export function getRamayanaExercisesByType(type: Exercise['type']): Exercise[] {
  return ramayanaExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Ramayana exercises
 */
export function getRamayanaTotalExerciseDuration(): number {
  return ramayanaExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Ramayana session
 */
export function getRamayanaRecommendedSequence(): Exercise[] {
  return [
    ramayanaExercises.find(e => e.title === 'The Seven Lamps Breath')!,
    ramayanaExercises.find(e => e.title === 'Meeting Rama and Sita')!,
    ramayanaExercises.find(e => e.title === 'Your Own Journey Home')!,
  ];
}

