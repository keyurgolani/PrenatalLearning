/**
 * Get Silk Road exercises by type
 */
export function getSilkRoadExercisesByType(type: Exercise['type']): Exercise[] {
  return silkRoadExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Silk Road exercises
 */
export function getSilkRoadTotalExerciseDuration(): number {
  return silkRoadExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Silk Road session
 */
export function getSilkRoadRecommendedSequence(): Exercise[] {
  return [
    silkRoadExercises.find(e => e.title === 'Camel Bell Breathing')!,
    silkRoadExercises.find(e => e.title === 'The Caravan Journey')!,
    silkRoadExercises.find(e => e.title === 'Your Thread in the Tapestry')!,
  ];
}

