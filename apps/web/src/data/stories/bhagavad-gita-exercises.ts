/**
 * Get Bhagavad Gita exercises by type
 */
export function getBhagavadGitaExercisesByType(type: Exercise['type']): Exercise[] {
  return bhagavadGitaExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Bhagavad Gita exercises
 */
export function getBhagavadGitaTotalExerciseDuration(): number {
  return bhagavadGitaExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Bhagavad Gita session
 */
export function getBhagavadGitaRecommendedSequence(): Exercise[] {
  return [
    bhagavadGitaExercises.find(e => e.title === 'The Gita Breath: Action and Surrender')!,
    bhagavadGitaExercises.find(e => e.title === 'Meeting Krishna')!,
    bhagavadGitaExercises.find(e => e.title === 'Your Dharma as a Parent')!,
  ];
}

