/**
 * Get Ayurveda exercises by type
 */
export function getAyurvedaExercisesByType(type: Exercise['type']): Exercise[] {
  return ayurvedaExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Ayurveda exercises
 */
export function getAyurvedaTotalExerciseDuration(): number {
  return ayurvedaExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for an Ayurveda session
 */
export function getAyurvedaRecommendedSequence(): Exercise[] {
  return [
    ayurvedaExercises.find(e => e.title === 'Dosha Balancing Pranayama')!,
    ayurvedaExercises.find(e => e.title === 'The Golden Ojas')!,
    ayurvedaExercises.find(e => e.title === 'Discovering Your Prakriti')!,
  ];
}

