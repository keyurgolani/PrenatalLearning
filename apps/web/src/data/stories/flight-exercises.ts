/**
 * Get Flight exercises by type
 */
export function getFlightExercisesByType(type: Exercise['type']): Exercise[] {
  return flightExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Flight exercises
 */
export function getFlightTotalExerciseDuration(): number {
  return flightExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Flight session
 */
export function getFlightRecommendedSequence(): Exercise[] {
  return [
    flightExercises.find(e => e.title === 'Wings of Breath')!,
    flightExercises.find(e => e.title === 'Soaring Through the Sky')!,
    flightExercises.find(e => e.title === 'Dreams of Flight')!,
  ];
}

