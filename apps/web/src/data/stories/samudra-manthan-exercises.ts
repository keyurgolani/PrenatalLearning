/**
 * Get Samudra Manthan exercises by type
 */
export function getSamudraManthanExercisesByType(type: Exercise['type']): Exercise[] {
  return samudraManthanExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Samudra Manthan exercises
 */
export function getSamudraManthanTotalExerciseDuration(): number {
  return samudraManthanExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Samudra Manthan session
 */
export function getSamudraManthanRecommendedSequence(): Exercise[] {
  return [
    samudraManthanExercises.find(e => e.title === 'The Churning Breath')!,
    samudraManthanExercises.find(e => e.title === 'The Ocean of Creation')!,
    samudraManthanExercises.find(e => e.title === 'Your Personal Churning')!,
  ];
}

