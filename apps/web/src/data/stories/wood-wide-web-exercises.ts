/**
 * Get Wood Wide Web exercises by type
 */
export function getWoodWideWebExercisesByType(type: Exercise['type']): Exercise[] {
  return woodWideWebExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Wood Wide Web exercises
 */
export function getWoodWideWebTotalExerciseDuration(): number {
  return woodWideWebExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Wood Wide Web session
 */
export function getWoodWideWebRecommendedSequence(): Exercise[] {
  return [
    woodWideWebExercises.find(e => e.title === 'Forest Breathing')!,
    woodWideWebExercises.find(e => e.title === 'Journey to the Mother Tree')!,
    woodWideWebExercises.find(e => e.title === 'Your Role as a Mother Tree')!,
  ];
}

