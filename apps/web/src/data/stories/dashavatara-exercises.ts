/**
 * Get Dashavatara exercises by type
 */
export function getDashavataraExercisesByType(type: Exercise['type']): Exercise[] {
  return dashavataraExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Dashavatara exercises
 */
export function getDashavataraTotalExerciseDuration(): number {
  return dashavataraExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Dashavatara session
 */
export function getDashavataraRecommendedSequence(): Exercise[] {
  return [
    dashavataraExercises.find(e => e.title === 'The Avatar Breath')!,
    dashavataraExercises.find(e => e.title === 'The Avatar Journey')!,
    dashavataraExercises.find(e => e.title === 'Your Inner Avatars')!,
  ];
}

