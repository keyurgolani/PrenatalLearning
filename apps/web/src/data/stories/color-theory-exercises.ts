/**
 * Get Color Theory exercises by type
 */
export function getColorTheoryExercisesByType(type: Exercise['type']): Exercise[] {
  return colorTheoryExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Color Theory exercises
 */
export function getColorTheoryTotalExerciseDuration(): number {
  return colorTheoryExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Color Theory session
 */
export function getColorTheoryRecommendedSequence(): Exercise[] {
  return [
    colorTheoryExercises.find(e => e.title === 'Rainbow Breathing')!,
    colorTheoryExercises.find(e => e.title === 'The Rainbow Meditation')!,
    colorTheoryExercises.find(e => e.title === 'The Emotional Palette Check-In')!,
  ];
}

