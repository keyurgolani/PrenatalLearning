/**
 * Get Yoga exercises by type
 */
export function getYogaExercisesByType(type: Exercise['type']): Exercise[] {
  return yogaExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Yoga exercises
 */
export function getYogaTotalExerciseDuration(): number {
  return yogaExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Yoga session
 */
export function getYogaRecommendedSequence(): Exercise[] {
  return [
    yogaExercises.find(e => e.title === 'Pranayama for Two')!,
    yogaExercises.find(e => e.title === 'Journey Through the Chakras')!,
    yogaExercises.find(e => e.title === 'The Meaning of Union')!,
  ];
}

