/**
 * Get Upanishads exercises by type
 */
export function getUpanishadsExercisesByType(type: Exercise['type']): Exercise[] {
  return upanishadsExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Upanishads exercises
 */
export function getUpanishadsTotalExerciseDuration(): number {
  return upanishadsExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for an Upanishads session
 */
export function getUpanishadsRecommendedSequence(): Exercise[] {
  return [
    upanishadsExercises.find(e => e.title === 'The Witness Breath')!,
    upanishadsExercises.find(e => e.title === 'The Ocean of Consciousness')!,
    upanishadsExercises.find(e => e.title === 'Discovering Your True Self')!,
  ];
}

export default upanishadsExercises;
