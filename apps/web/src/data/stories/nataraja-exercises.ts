/**
 * Get Nataraja exercises by type
 */
export function getNatarajaExercisesByType(type: Exercise['type']): Exercise[] {
  return natarajaExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Nataraja exercises
 */
export function getNatarajaTotalExerciseDuration(): number {
  return natarajaExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Nataraja session
 */
export function getNatarajaRecommendedSequence(): Exercise[] {
  return [
    natarajaExercises.find(e => e.title === 'The Five Acts Breath')!,
    natarajaExercises.find(e => e.title === 'The Cosmic Dance Visualization')!,
    natarajaExercises.find(e => e.title === 'Your Personal Dance')!,
  ];
}

