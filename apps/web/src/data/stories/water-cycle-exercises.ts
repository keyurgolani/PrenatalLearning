/**
 * Get Water Cycle exercises by type
 */
export function getWaterCycleExercisesByType(type: Exercise['type']): Exercise[] {
  return waterCycleExercises.filter(exercise => exercise.type === type);
}

/**
 * Get total duration of all Water Cycle exercises
 */
export function getWaterCycleTotalExerciseDuration(): number {
  return waterCycleExercises.reduce((total, exercise) => total + exercise.duration, 0);
}

/**
 * Get a recommended exercise sequence for a Water Cycle session
 */
export function getWaterCycleRecommendedSequence(): Exercise[] {
  return [
    waterCycleExercises.find(e => e.title === 'Water Cycle Breathing')!,
    waterCycleExercises.find(e => e.title === 'Journey Through the Water Cycle')!,
    waterCycleExercises.find(e => e.title === 'Ancient Water Within You')!,
  ];
}

